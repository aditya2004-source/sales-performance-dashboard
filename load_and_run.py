"""Load the Superstore CSV into SQLite, run the cleaning + business-question SQL files,
and save every query result to results/ (CSV + one Markdown summary)."""
import re
import sqlite3
import pandas as pd

DB = "superstore.db"
con = sqlite3.connect(DB)
con.executescript(open("sql/01_create_table.sql").read())

df = pd.read_csv("data/superstore.csv", encoding="latin1")
df.columns = [re.sub(r"[^a-z]+", "_", c.lower()).strip("_") for c in df.columns]
df["order_date"] = pd.to_datetime(df["order_date"]).dt.strftime("%Y-%m-%d")
df["ship_date"] = pd.to_datetime(df["ship_date"]).dt.strftime("%Y-%m-%d")
df.to_sql("orders", con, if_exists="append", index=False)


def run_file(path, prefix):
    blocks = re.split(r"\n(?=-- (?:\d+\.|Q\d+\.))", open(path).read())
    out = []
    for block in blocks:
        title = re.match(r"-- ((?:\d+\.|Q\d+\.).*)", block)
        sql = "\n".join(l for l in block.splitlines() if not l.startswith("--")).strip()
        if not title or not sql:
            continue
        if sql.upper().startswith(("DELETE", "UPDATE")):
            n = con.execute(sql).rowcount
            con.commit()
            out.append((title.group(1), pd.DataFrame({"rows_affected": [n]})))
            continue
        res = pd.read_sql_query(sql, con)
        key = title.group(1).split(".")[0]
        res.to_csv(f"results/{prefix}_{key.lower()}.csv", index=False)
        out.append((title.group(1), res))
    return out


md = ["# Query Results\n", "_Generated by `load_and_run.py`._\n"]
for header, path, prefix in [("Data Cleaning", "sql/02_data_cleaning.sql", "clean"),
                             ("Business Questions", "sql/03_business_questions.sql", "bq")]:
    md.append(f"\n## {header}\n")
    for title, res in run_file(path, prefix):
        md.append(f"\n### {title}\n\n{res.astype(object).to_markdown(index=False, floatfmt=',.2f', intfmt=',')}\n")
open("results/query_results.md", "w").write("".join(md))

# Clean data export for Power BI
pd.read_sql_query("SELECT * FROM orders", con).to_csv("data/superstore_clean.csv", index=False)
print("Done:", pd.read_sql_query("SELECT COUNT(*) n FROM orders", con).n[0], "clean rows")
